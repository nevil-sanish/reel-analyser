#!/usr/bin/env python3
"""Draws the Reel Analyser launcher icon (v1.1) as Android vector drawables, and an SVG preview.

A charcoal disc, a thin gold ring, a ring of Greek key (meander) and a gold play mark. The full build is gold, the semi build is
the same mark in silver. The same geometry is drawn in lib/ui/theme.dart (BrandMark): keep the numbers in step.

  python3 tool/make_icon.py            # writes android/app/src/{main,semi}/res/drawable/ic_launcher_*.xml
  python3 tool/make_icon.py --preview  # also writes /tmp/icon_full.svg and /tmp/icon_semi.svg
"""
import math, sys

C = 54.0                      # centre of the 108 x 108 viewport
R_RING, R_IN, R_OUT, N, R_INNER = 31.0, 21.5, 26.5, 24, 19.0
KEY = [(0, 1), (0, 0), (0.72, 0), (0.72, 0.66), (0.32, 0.66), (0.32, 0.33), (0.5, 0.33)]  # (u along, v from the inner edge)


def pt(theta, r):
    return C + r * math.cos(theta), C + r * math.sin(theta)


def meander_path():
    """One continuous polyline per key, bent round the circle. v=1 sits on the inner radius, v=0 on the outer."""
    d = []
    w = 2 * math.pi / N
    for k in range(N):
        a0 = -math.pi / 2 + k * w
        prev = None
        for (u, v) in KEY:
            r = R_IN + (1 - v) * (R_OUT - R_IN)
            th = a0 + u * w
            if prev is None:
                d.append("M%.2f,%.2f" % pt(th, r))
            else:
                pu, pv = prev
                if abs(pv - v) < 1e-9:  # same radius: follow the arc in small steps
                    steps = max(2, int(abs(u - pu) * 6))
                    for s in range(1, steps + 1):
                        d.append("L%.2f,%.2f" % pt(a0 + (pu + (u - pu) * s / steps) * w, r))
                else:
                    d.append("L%.2f,%.2f" % pt(th, r))
            prev = (u, v)
    return "".join(d)


def circle_path(r):
    return "M%.2f,%.2fa%.2f,%.2f 0 1 1 %.2f,0a%.2f,%.2f 0 1 1 %.2f,0z" % (C - r, C, r, r, 2 * r, r, r, -2 * r)


PLAY = "M%.2f,%.2fL%.2f,%.2fL%.2f,%.2fz" % (C - 5.4, C - 9.2, C - 5.4, C + 9.2, C + 10.2, C)

PALETTES = {
    "main": dict(bg0="#FF1F1C14", bg1="#FF0C0B08", g0="#FF8A6410", g1="#FFC9A227", g2="#FFEFD98F"),
    "semi": dict(bg0="#FF1A1F29", bg1="#FF0A0C11", g0="#FF6F7886", g1="#FFB4BCC8", g2="#FFF1F3F6"),
}


def grad(kind, p, attr):
    return ('    <aapt:attr name="android:%s">\n      <gradient android:type="linear" android:startX="18" android:startY="90" android:endX="90" android:endY="18">\n'
            '        <item android:offset="0" android:color="%s"/>\n        <item android:offset="0.5" android:color="%s"/>\n        <item android:offset="1" android:color="%s"/>\n'
            '      </gradient>\n    </aapt:attr>\n') % (attr, p["g0"], p["g1"], p["g2"])


def background(p):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/make_icon.py: charcoal with a faint glow. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            '  <path android:pathData="M0,0h108v108h-108z">\n    <aapt:attr name="android:fillColor">\n'
            '      <gradient android:type="radial" android:centerX="54" android:centerY="48" android:gradientRadius="72">\n'
            '        <item android:offset="0" android:color="%s"/>\n        <item android:offset="1" android:color="%s"/>\n'
            '      </gradient>\n    </aapt:attr>\n  </path>\n</vector>\n') % (p["bg0"], p["bg1"])


def foreground(p):
    out = ['<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/make_icon.py: gold (or silver) ring, Greek key and play mark. Inside the 66dp safe zone. -->\n'
           '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n']
    out.append('  <path android:strokeWidth="0.9" android:fillColor="#00000000" android:pathData="%s">\n%s  </path>\n' % (circle_path(R_RING), grad("l", p, "strokeColor")))
    out.append('  <path android:strokeWidth="0.55" android:strokeAlpha="0.6" android:fillColor="#00000000" android:pathData="%s">\n%s  </path>\n' % (circle_path(R_INNER), grad("l", p, "strokeColor")))
    out.append('  <path android:strokeWidth="1.1" android:strokeLineJoin="miter" android:fillColor="#00000000" android:pathData="%s">\n%s  </path>\n' % (meander_path(), grad("l", p, "strokeColor")))
    out.append('  <path android:strokeWidth="2.4" android:strokeLineJoin="round" android:pathData="%s">\n%s%s  </path>\n</vector>\n' % (PLAY, grad("l", p, "fillColor"), grad("l", p, "strokeColor")))
    return "".join(out)


def monochrome():
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/make_icon.py: the themed-icon silhouette. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            '  <path android:strokeColor="#FF000000" android:strokeWidth="1.0" android:fillColor="#00000000" android:pathData="%s"/>\n'
            '  <path android:strokeColor="#FF000000" android:strokeWidth="1.2" android:fillColor="#00000000" android:pathData="%s"/>\n'
            '  <path android:strokeColor="#FF000000" android:strokeWidth="2.4" android:strokeLineJoin="round" android:fillColor="#FF000000" android:pathData="%s"/>\n</vector>\n'
            ) % (circle_path(R_RING), meander_path(), PLAY)


def svg(p):
    g = lambda i: p["g%d" % i][3:]
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432"><defs>'
            '<radialGradient id="bg" cx="54" cy="48" r="72" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#%s"/><stop offset="1" stop-color="#%s"/></radialGradient>'
            '<linearGradient id="g" x1="18" y1="90" x2="90" y2="18" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#%s"/><stop offset=".5" stop-color="#%s"/><stop offset="1" stop-color="#%s"/></linearGradient></defs>'
            '<rect width="108" height="108" fill="url(#bg)"/>'
            '<path d="%s" fill="none" stroke="url(#g)" stroke-width="0.9"/><path d="%s" fill="none" stroke="url(#g)" stroke-width="0.55" opacity=".6"/>'
            '<path d="%s" fill="none" stroke="url(#g)" stroke-width="1.1"/><path d="%s" fill="url(#g)" stroke="url(#g)" stroke-width="2.4" stroke-linejoin="round"/></svg>'
            ) % (p["bg0"][3:], p["bg1"][3:], g(0), g(1), g(2), circle_path(R_RING), circle_path(R_INNER), meander_path(), PLAY)


if __name__ == "__main__":
    base = "android/app/src/%s/res/drawable/"
    for flavour, p in PALETTES.items():
        open(base % flavour + "ic_launcher_background.xml", "w").write(background(p))
        open(base % flavour + "ic_launcher_foreground.xml", "w").write(foreground(p))
        if "--preview" in sys.argv:
            open("/tmp/icon_%s.svg" % ("full" if flavour == "main" else "semi"), "w").write(svg(p))
    open(base % "main" + "ic_launcher_monochrome.xml", "w").write(monochrome())
    print("icons written")
